-- Ejecutar con F5 en SQL Developer, conectado al MISMO esquema de negocio.
-- Oracle 12.2+ (JSON_OBJECT). No modifica paquetes existentes.
SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

BEGIN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE FB_SYNC_VERSION_PJM START WITH 1 INCREMENT BY 1 NOCYCLE';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE FB_SYNC_TABLES_PJM (
      TABLA VARCHAR2(128) PRIMARY KEY, COLECCION VARCHAR2(128) NOT NULL UNIQUE,
      PK_COLUMNAS VARCHAR2(2000) NOT NULL, ACTIVA NUMBER(1) DEFAULT 1 NOT NULL)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE FB_SYNC_OUTBOX_PJM (
      ID_EVENTO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      TABLA VARCHAR2(128) NOT NULL, PK_JSON VARCHAR2(4000) NOT NULL,
      CREADO TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      INTENTOS NUMBER DEFAULT 0 NOT NULL,
      PROXIMO_INTENTO TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      ULTIMO_ERROR VARCHAR2(1000))';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX FB_SYNC_PEND_PJM ON FB_SYNC_OUTBOX_PJM(PROXIMO_INTENTO,ID_EVENTO)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE FB_SYNC_LOCK_PJM (ID NUMBER PRIMARY KEY)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
MERGE INTO FB_SYNC_LOCK_PJM t USING (SELECT 1 ID FROM DUAL) s ON (t.ID=s.ID)
WHEN NOT MATCHED THEN INSERT (ID) VALUES(s.ID);
COMMIT;

-- Registro explícito: solo tablas de los módulos del proyecto.
-- Las tablas opcionales ausentes se informan, sin inventar su estructura.
DECLARE
    v_new VARCHAR2(16000);
    v_old VARCHAR2(16000);
    v_cols VARCHAR2(2000);
    v_sql VARCHAR2(32767);
    v_collection VARCHAR2(128);
    v_exists NUMBER;
    v_bad NUMBER;
    v_errors NUMBER;
    v_count NUMBER := 0;
BEGIN
    FOR t IN (
      SELECT COLUMN_VALUE tabla FROM TABLE(SYS.ODCIVARCHAR2LIST(
        'SUCURSAL_PJM','PRODUCTO_PJM','RECETA_PJM','PEDIDO_PJM',
        'DETALLE_PEDIDO_PJM','PRODUCCION_PJM','DETALLE_PRODUCCION_PJM',
        'INCIDENTES_RUTA_PJM','AUDITORIA_PJM',
        'CLIENTE_WEB','CLIENTE_E','ORDEN_E','PRODUCTO','FACTURA','DETALLE_FACTURA'
      ))
      UNION
      -- Tablas adicionales usadas por los paquetes de los managers de plantilla.
      SELECT DISTINCT REFERENCED_NAME FROM USER_DEPENDENCIES
      WHERE REFERENCED_TYPE='TABLE' AND REFERENCED_OWNER=USER
      AND NAME IN ('PKG_CATALOGOS','PKG_CONVERTIDOR_MONEDA','PKG_EJEMPLO',
                   'PKG_EJEMPLOS','PKG_FACTURA','PKG_INCIDENTES_PJM',
                   'PKG_PEDIDOS_PJM','PKG_PRODUCCION_PJM','PKG_PRODUCTOS_PJM',
                   'PKG_REPORTES_PJM','PKG_SUCURSALES_PJM')
      AND REFERENCED_NAME NOT LIKE 'FB_SYNC_%'
      AND NOT REGEXP_LIKE(REFERENCED_NAME,'USUARIO|PASSWORD|CREDENCIAL|TOKEN|SECRET','i')
    ) LOOP
      SELECT COUNT(*) INTO v_exists FROM USER_TABLES WHERE TABLE_NAME=t.tabla;
      IF v_exists=0 THEN
        DBMS_OUTPUT.PUT_LINE('AUSENTE: '||t.tabla);
        CONTINUE;
      END IF;
      v_new := NULL; v_old := NULL; v_cols := NULL; v_bad := 0;
      FOR k IN (
        SELECT cc.COLUMN_NAME,tc.DATA_TYPE
        FROM USER_CONSTRAINTS c
        JOIN USER_CONS_COLUMNS cc ON cc.CONSTRAINT_NAME=c.CONSTRAINT_NAME
        JOIN USER_TAB_COLUMNS tc ON tc.TABLE_NAME=cc.TABLE_NAME AND tc.COLUMN_NAME=cc.COLUMN_NAME
        WHERE c.TABLE_NAME=t.tabla AND c.CONSTRAINT_TYPE='P' AND c.STATUS='ENABLED'
        ORDER BY cc.POSITION
      ) LOOP
        IF k.DATA_TYPE NOT IN ('NUMBER','VARCHAR2','CHAR','NVARCHAR2','NCHAR') THEN v_bad:=1; END IF;
        IF v_new IS NOT NULL THEN
          v_new:=v_new||','; v_old:=v_old||','; v_cols:=v_cols||',';
        END IF;
        v_new:=v_new||''''||k.COLUMN_NAME||''' VALUE :NEW.'||DBMS_ASSERT.SIMPLE_SQL_NAME(k.COLUMN_NAME);
        v_old:=v_old||''''||k.COLUMN_NAME||''' VALUE :OLD.'||DBMS_ASSERT.SIMPLE_SQL_NAME(k.COLUMN_NAME);
        v_cols:=v_cols||k.COLUMN_NAME;
      END LOOP;
      IF v_cols IS NULL OR v_bad=1 THEN
        DBMS_OUTPUT.PUT_LINE('NO HABILITADA (falta PK compatible): '||t.tabla);
        CONTINUE;
      END IF;
      v_collection := CASE t.tabla
        WHEN 'SUCURSAL_PJM' THEN 'sucursales'
        WHEN 'PRODUCTO_PJM' THEN 'productos'
        WHEN 'RECETA_PJM' THEN 'recetas'
        WHEN 'PEDIDO_PJM' THEN 'pedidos'
        WHEN 'DETALLE_PEDIDO_PJM' THEN 'detalles_pedido'
        WHEN 'PRODUCCION_PJM' THEN 'producciones'
        WHEN 'DETALLE_PRODUCCION_PJM' THEN 'detalles_produccion'
        WHEN 'INCIDENTES_RUTA_PJM' THEN 'incidentes'
        WHEN 'AUDITORIA_PJM' THEN 'auditoria'
        ELSE 'plantilla_'||LOWER(t.tabla) END;

      v_sql := 'CREATE OR REPLACE TRIGGER FBS_'||SUBSTR(t.tabla,1,25)||
        ' AFTER INSERT OR UPDATE OR DELETE ON '||DBMS_ASSERT.SIMPLE_SQL_NAME(t.tabla)||
        ' FOR EACH ROW DECLARE v_new VARCHAR2(4000); v_old VARCHAR2(4000); BEGIN '||
        'IF INSERTING OR UPDATING THEN SELECT JSON_OBJECT('||v_new||
        ' RETURNING VARCHAR2(4000)) INTO v_new FROM DUAL; END IF; '||
        'IF DELETING OR UPDATING THEN SELECT JSON_OBJECT('||v_old||
        ' RETURNING VARCHAR2(4000)) INTO v_old FROM DUAL; END IF; '||
        'IF INSERTING OR UPDATING THEN INSERT INTO FB_SYNC_OUTBOX_PJM(TABLA,PK_JSON) VALUES('''||
        t.tabla||''',v_new); END IF; '||
        'IF DELETING OR (UPDATING AND v_old<>v_new) THEN '||
        'INSERT INTO FB_SYNC_OUTBOX_PJM(TABLA,PK_JSON) VALUES('''||t.tabla||''',v_old); END IF; END;';
      EXECUTE IMMEDIATE v_sql;
      SELECT COUNT(*) INTO v_errors FROM USER_ERRORS
        WHERE NAME='FBS_'||SUBSTR(t.tabla,1,25) AND TYPE='TRIGGER';
      IF v_errors>0 THEN
        EXECUTE IMMEDIATE 'ALTER TRIGGER FBS_'||SUBSTR(t.tabla,1,25)||' DISABLE';
        RAISE_APPLICATION_ERROR(-20001,'Error compilando trigger de '||t.tabla||'. Revisar USER_ERRORS.');
      END IF;
      MERGE INTO FB_SYNC_TABLES_PJM dest
      USING (SELECT t.tabla tabla,v_collection coleccion,v_cols columnas FROM DUAL) src
      ON (dest.TABLA=src.tabla)
      WHEN MATCHED THEN UPDATE SET dest.COLECCION=src.coleccion,dest.PK_COLUMNAS=src.columnas,dest.ACTIVA=1
      WHEN NOT MATCHED THEN INSERT(TABLA,COLECCION,PK_COLUMNAS,ACTIVA)
        VALUES(src.tabla,src.coleccion,src.columnas,1);
      COMMIT;
      v_count:=v_count+1;
      DBMS_OUTPUT.PUT_LINE('HABILITADA: '||t.tabla||' -> '||v_collection||' (PK: '||v_cols||')');
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('Total de tablas habilitadas: '||v_count);
END;
/
SELECT TABLA,COLECCION,PK_COLUMNAS,ACTIVA FROM FB_SYNC_TABLES_PJM ORDER BY TABLA;
SELECT NAME,LINE,POSITION,TEXT FROM USER_ERRORS WHERE NAME LIKE 'FBS_%' ORDER BY NAME,SEQUENCE;
